#!/usr/bin/env python3
"""Render local THUDM configs, record changes, and create seed-grouped research splits."""
import collections
import copy
import hashlib
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def differences(before, after, prefix=""):
    result = {}
    for key in sorted(set(before) | set(after)):
        path = f"{prefix}.{key}" if prefix else key
        a, b = before.get(key), after.get(key)
        if isinstance(a, dict) and isinstance(b, dict):
            result.update(differences(a, b, path))
        elif a != b:
            result[path] = {"upstream": a, "local": b}
    return result


def main():
    paths = json.loads((ROOT / "configs/paths.json").read_text())
    source = ROOT / "SCALE-CUA/scalecua_rl/examples/training/configs/qw3vl_train_std.yaml"
    original = yaml.safe_load(source.read_text())
    reports = {}
    for name, gpus, concurrency in [("smoke-6gpu", 6, 8), ("baseline-6gpu", 6, 16), ("baseline-16gpu", 16, 32)]:
        cfg = copy.deepcopy(original)
        cfg.update(model_path=paths["model_dir"], save_path=str(ROOT / "runs/checkpoints"),
                   project_name="thudm-scalecua-osworld", run_name=name, group_name="qwen3vl-osworld-original-grpo",
                   num_gpu_per_mach=6 if gpus == 6 else 8, rollout_ratio=1 / 3 if gpus == 6 else 0.25,
                   metrics_log_dir=str(ROOT / "runs/metrics" / name))
        cfg["train"]["concurrency"] = concurrency
        cfg["task"]["base_url"] = paths.get("controller_url") or "http://127.0.0.1:5020/api"
        cfg["task"]["fallback_base_url"] = cfg["task"]["base_url"]
        cfg["dynamic_sampling"]["initial_pass_rate_file"] = str(ROOT / "configs/initial_pass_rate.osworld-rl.json")
        if name.startswith("smoke"):
            # Upstream starts at step 1 and loops while step < max_steps.
            cfg.update(max_steps=3, save_interval=2)
            cfg["train"].update(batch_size=2, n=4)
            cfg["dynamic_sampling"].update(enabled=False, initial_pass_rate_file=None)
            cfg["rollout"]["server_args"].update(max_model_len=40960, mm_processor_cache_gb=4, max_num_seqs=4)
        target = ROOT / "configs" / f"qwen3vl-osworld-{name}.yaml"
        target.write_text("# Generated by scripts/prepare_configs.py. Run preflight_rl.py before launch.\n" + yaml.safe_dump(cfg, sort_keys=False))
        rollout_gpus = int(gpus * cfg["rollout_ratio"])
        assert rollout_gpus % cfg["rollout"]["tp_size"] == 0
        assert (gpus - rollout_gpus) % cfg["actor"]["tensor_model_parallel_size"] == 0
        reports[name] = {"gpus": gpus, "rollout_gpus": rollout_gpus, "actor_and_ref_gpus": gpus - rollout_gpus,
                         "status": "prepared; not launched or memory-profiled", "changes": differences(original, cfg)}
    # Keep the independently maintained local bring-up config in the audit.
    # Regenerating the formal configs must not erase its recorded differences.
    for local_config in sorted((ROOT / "configs").glob("qwen3vl-osworld-local-*.yaml")):
        name = local_config.stem.removeprefix("qwen3vl-osworld-")
        local = yaml.safe_load(local_config.read_text())
        result_path = ROOT / ("reports/smoke-online-rl-signal.json" if name == "local-signal-1step" else "reports/smoke-online-rl.json")
        result = json.loads(result_path.read_text()) if result_path.exists() else {}
        reports[name] = {
            "gpus": 6, "rollout_gpus": 2, "actor_and_ref_gpus": 4,
            "status": "online training chain verified; check gradient/signal in result" if result.get("passed") else "bring-up; see reports/bringup-attempts.json",
            "result": str(result_path.relative_to(ROOT)),
            "scope": "Local eval-agent adapter and software VM; not exact paper reproduction",
            "changes": differences(original, local),
        }
    (ROOT / "reports/config-differences.json").write_text(json.dumps(reports, indent=2) + "\n")

    # Leave the 2,049-task reproduction pool unchanged. These separate lists are
    # for later algorithm development, keeping all variants of a seed together.
    by_seed = collections.defaultdict(list)
    seed_domains = collections.defaultdict(collections.Counter)
    index_domains = {}
    for file in sorted((ROOT / "data/ScaleCUA/osworld/rl_tasks").rglob("*.json")):
        task = json.loads(file.read_text())
        index = f"{file.parent.name}_{task['new_id']}"
        by_seed[task["id"]].append(index)
        index_domains[index] = file.parent.name
        seed_domains[task["id"]][file.parent.name] += 1
    domains = collections.defaultdict(dict)
    for seed, indices in by_seed.items():
        # A seed can appear under multiple application folders. Group globally
        # first, then use its most frequent domain only for stratification.
        domain = sorted(seed_domains[seed], key=lambda d: (-seed_domains[seed][d], d))[0]
        domains[domain][seed] = indices
    splits = {name: {"task_indices": [], "base_ids": []} for name in ["train", "dev", "test"]}
    for domain, groups in domains.items():
        seeds = sorted(groups, key=lambda seed: hashlib.sha256(("cua-rl-v1:" + seed).encode()).hexdigest())
        count = max(1, len(seeds) // 10)
        for name, selected in [("dev", seeds[:count]), ("test", seeds[count:2*count]), ("train", seeds[2*count:])]:
            for seed in selected:
                splits[name]["base_ids"].append(seed)
                splits[name]["task_indices"].extend(groups[seed])
    assert sum(len(v["task_indices"]) for v in splits.values()) == 2049
    # Explicit client list for all four Frontier initialization passes.
    (ROOT / "configs/rl-indices.json").write_text(json.dumps(sorted(index_domains), indent=2) + "\n")
    for a, b in [("train", "dev"), ("train", "test"), ("dev", "test")]:
        assert not (set(splits[a]["base_ids"]) & set(splits[b]["base_ids"]))
        assert not (set(splits[a]["task_indices"]) & set(splits[b]["task_indices"]))
    for value in splits.values():
        value["task_indices"].sort()
        value["base_ids"].sort()
    split_dir = ROOT / "configs/research-splits"
    split_dir.mkdir(exist_ok=True)
    for name, value in splits.items():
        (split_dir / f"{name}-indices.json").write_text(json.dumps(value["task_indices"], indent=2) + "\n")
        # Missing dictionary keys mean 'load everything' in the upstream loader,
        # so explicitly include even domains with zero selected tasks.
        examples = {domain: [] for domain in sorted(set(index_domains.values()))}
        for index in value["task_indices"]:
            examples[index_domains[index]].append(index)
        (split_dir / f"{name}-examples.json").write_text(json.dumps(examples, indent=2) + "\n")
    manifest = {"protocol": "optional research split; not the official full-pool reproduction recipe",
                "grouping": "base id, stratified by domain; deterministic SHA256 order, approximately 80/10/10",
                "warning": "The released RL pool derives from OSWorld seed tasks; this split does not make the official 361-task evaluation an unseen-seed benchmark.",
                "splits": splits}
    (split_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"configs": list(reports), "research_split_sizes": {k: len(v["task_indices"]) for k, v in splits.items()}}))


if __name__ == "__main__":
    main()
